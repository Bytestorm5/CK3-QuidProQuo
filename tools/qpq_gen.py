def fmt_shown(s, P, A):
    """An offer condition with explicit payer/agent scopes (for the Propose-a-Pact panel)."""
    return s.replace("{P}", P).replace("{A}", A)


def fmt(s, k):
    return s.replace("{P}", payer_scope(k)).replace("{A}", agent_scope(k)).replace("{K}", k["key"])


