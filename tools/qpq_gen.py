def ctx_block(party, tgt):
    if not tgt:
        return ""
    lines = ["if = {", "\tlimit = { exists = %s }" % tgt]
    for trig, add in CTX_CHECKS:
        lines.append("\tif = {")
        lines.append("\t\tlimit = { %s }" % trig.format(p=party, t=tgt))
        lines.append("\t\tadd = %d" % add)
        lines.append("\t}")
    lines.append("}")
    return "\n".join("\t" + l for l in lines) + "\n"


def tier_value(k, role):
    party = payer_scope(k) if role == "payer" else agent_scope(k)
    base = k["payer_base"] if role == "payer" else k["agent_base"]
    use_ctx = k["payer_ctx"] if role == "payer" else k["agent_ctx"]
    out = "qpq_%s_%s_tier_value = {\n\tvalue = %d\n" % (k["key"], role, base)
    if use_ctx:
        out += ctx_block(party, target_expr(k))
    adj = k.get("payer_adj" if role == "payer" else "agent_adj")
    if adj:
        out += block(adj, 1)
    out += "\tmin = 0\n\tmax = 5\n}\n"
    return out


