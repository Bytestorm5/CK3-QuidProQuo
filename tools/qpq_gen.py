TRAIT_MODS = [("honest", -6), ("just", -5), ("deceitful", 4), ("arbitrary", 3), ("schemer", 3), ("paranoid", -3)]
AGENT_INIT_BASE = 35
LOSS_AVERSION = goals.LOSS_AVERSION
# A deed done for them that they have no particular wish for (no goal archetype speaks to it) is still worth a
# share of the deed's own size (base tier and effort, as a doer would weigh it), within bounds. An AI judges by
# what it gets and gives, never by the other party's purse, rank or circumstances.
WORTH_SHARE, WORTH_MIN, WORTH_MAX = 0.4, 5, 25
# Archetypes whose goal says all a deed is worth to the one who would pay for it
WISH_ARCHETYPES = {"war", "harm", "favour", "war_side", "loss_title", "loss_artifact"}
# ...except deeds that weaken the side the payer is at war with (worth the strength taken off it, against the
# payer's own), and deeds whose harm brings the payer a gain of its own (a regency)
WAR_HELP = {"turncoat", "faithless_ally"}
INTRINSIC = {"coup_pact"}


# A deal's term (scope:qpq_term_months, chosen in the panel; otherwise the deed's usual term) weighs on it by
# what kind of deed it is:
#   condition  something to achieve by the deadline (a war won, a county converted): less time is harder,
#              more time easier, within bounds
#   perform    a single act: a little harder when rushed
#   restraint  a promise kept for the term: the longer, the more it costs the one bound, and the more it is
#              worth to the one it protects; shorter than usual, down to half; longer, half again for every
#              usual term (or five years, if that is longer) beyond it
# The one who pays for a deed to be done (condition, perform) wants it soon: three in a hundred of its worth for
# every year sooner or later than usual, from 0.6 to 1.15 of it.
# And payment on delivery waits: the whole term for a promise, about half of it for the rest.
TERM_SHAPE = {"condition": (0.5, -0.3, 1.5), "perform": (0.25, -0.15, 0.75)}
TERM_YEARS = goals.TERM_YEARS


def term_values(k):
    key, T0, mode = k["key"], k["term"], k["mode"]
    out = ""
    if key == "barter":
        out += "qpq_%s_time_value = {\n\tvalue = 0\n}\n" % key
        out += "qpq_%s_term_worth_mult_value = {\n\tvalue = 1\n}\n" % key
    elif mode == "restraint":
        # how much a promise of this length weighs, against one of the usual length
        out += ("qpq_%s_term_worth_mult_value = {\n\tvalue = 1\n\tif = {\n\t\tlimit = { exists = scope:qpq_term_months }\n"
                "\t\tif = {\n\t\t\tlimit = { scope:qpq_term_months <= %d }\n\t\t\tvalue = scope:qpq_term_months\n"
                "\t\t\tdivide = %d\n\t\t\tmultiply = 0.5\n\t\t\tadd = 0.5\n\t\t}\n"
                "\t\telse = {\n\t\t\tvalue = scope:qpq_term_months\n\t\t\tsubtract = %d\n\t\t\tdivide = %d\n"
                "\t\t\tmultiply = 0.5\n\t\t\tadd = 1\n\t\t}\n\t}\n}\n") % (key, T0, T0, T0, max(T0, 60))
        out += ("qpq_%s_time_value = {\n\tvalue = qpq_%s_term_worth_mult_value\n\tsubtract = 1\n"
                "\tmultiply = qpq_%s_base_demand_value\n}\n") % (key, key, key)
    else:
        scale, lo, hi = TERM_SHAPE[mode]
        out += ("qpq_%s_time_value = {\n\tvalue = 0\n\tif = {\n\t\tlimit = { exists = scope:qpq_term_months }\n"
                "\t\tvalue = qpq_%s_base_demand_value\n\t\tmultiply = {\n\t\t\tvalue = %d\n\t\t\tdivide = scope:qpq_term_months\n"
                "\t\t\tsubtract = 1\n\t\t\tmultiply = %s\n\t\t\tmin = %s\n\t\t\tmax = %s\n\t\t}\n\t}\n}\n") % (
                    key, key, T0, scale, lo, hi)
        # sooner is better, to the one who wants it done
        out += ("qpq_%s_term_worth_mult_value = {\n\tvalue = 1\n\tif = {\n\t\tlimit = { exists = scope:qpq_term_months }\n"
                "\t\tadd = {\n\t\t\tvalue = %d\n\t\t\tsubtract = scope:qpq_term_months\n\t\t\tmultiply = 0.0025\n\t\t}\n"
                "\t}\n\tmin = 0.6\n\tmax = 1.15\n}\n") % (key, T0)
    # what waiting for payment on delivery costs the one paid: three points, and one and a half a year waited
    share = 1 if mode == "restraint" else 0.5
    out += ("qpq_%s_wait_value = {\n\tvalue = %d\n\tif = {\n\t\tlimit = { exists = scope:qpq_term_months }\n"
            "\t\tvalue = scope:qpq_term_months\n\t}\n\tmultiply = %s\n\tdivide = 12\n\tmultiply = -1.5\n\tadd = -3\n"
            "\tmin = -25\n}\n") % (key, T0, share)
    return out


def goods_cost_body(G, R, price):
    """Script value body: what handing over the goods ticked (scope:qpq_o_*) costs G, who gives them to R, in
    acceptance points before loss aversion. Gold is five points a month of G's own stake, however much: no flat
    part, no cap, so an exchange of goods is always weighed sum for sum."""
    s = "\tvalue = 0\n"
    s += ("\tif = {\n\t\tlimit = { scope:qpq_o_gold ?= yes }\n\t\tadd = {\n\t\t\tvalue = 0\n"
          "\t\t\tif = {\n\t\t\t\tlimit = { exists = scope:qpq_price }\n\t\t\t\tadd = scope:qpq_price\n\t\t\t}\n"
          "\t\t\telse = {\n\t\t\t\tadd = %(price)s\n\t\t\t}\n"
          "\t\t\tdivide = {\n\t\t\t\tvalue = %(G)s.qpq_stake_value\n\t\t\t\tmultiply = 6\n\t\t\t\tmin = 5\n\t\t\t}\n"
          "\t\t\tmultiply = 30\n"
          "\t\t\tif = {\n\t\t\t\tlimit = { %(G)s = { has_trait = greedy } }\n\t\t\t\tmultiply = 1.3\n\t\t\t}\n"
          "\t\t\tif = {\n\t\t\t\tlimit = { %(G)s = { has_trait = generous } }\n\t\t\t\tmultiply = 0.8\n\t\t\t}\n\t\t}\n"
          # paying later, if at all, is easier on the one who pays
          "\t\tif = {\n\t\t\tlimit = { scope:qpq_o_on_delivery ?= yes }\n\t\t\tadd = -6\n\t\t}\n"
          "\t\tif = {\n\t\t\tlimit = { scope:qpq_o_split ?= yes }\n\t\t\tadd = -2\n\t\t}\n"
          "\t\tif = {\n\t\t\tlimit = { scope:qpq_o_stipend ?= yes }\n\t\t\tadd = -4\n\t\t}\n\t}\n") % {"G": G, "price": price}
    def good(o, body):
        return "\tif = {\n\t\tlimit = { scope:qpq_o_%s ?= yes }\n%s\t}\n" % (o, body)
    # a county, dearer when it is one of their last
    s += good("land", "\t\tadd = %s\n" % ("qpq_goods_land_cost_value" if G == "scope:actor" else "qpq_goods_land_cost_rec_value"))
    s += good("claim", "\t\tadd = 6\n")
    s += good("office", "\t\tadd = 12\n")
    s += good("release_hook", "\t\tadd = 14\n\t\tif = {\n\t\t\tlimit = { %s = { has_strong_hook = %s } }\n\t\t\tadd = 31\n\t\t}\n" % (G, R))
    # calling in a hook spends it
    s += good("hook", "\t\tadd = 14\n\t\tif = {\n\t\t\tlimit = { %s = { has_strong_hook = %s } }\n\t\t\tadd = 31\n\t\t}\n" % (G, R))
    # their word is a hook on themselves: about what holding one is worth, more to the honest who will keep it
    s += good("my_word", "\t\tadd = 12\n\t\tif = {\n\t\t\tlimit = { %s = { has_trait = honest } }\n\t\t\tadd = 4\n\t\t}\n" % G)
    s += good("secret", "\t\tif = {\n\t\t\tlimit = { exists = scope:qpq_gift_secret_points }\n\t\t\tadd = scope:qpq_gift_secret_points\n\t\t}\n"
                        "\t\telse = {\n\t\t\tadd = 12\n\t\t}\n")
    s += good("contract", "\t\tadd = 22\n\t\tif = {\n\t\t\tlimit = { %s = { has_trait = greedy } }\n\t\t\tadd = 5\n\t\t}\n" % G)
    s += good("succession", "\t\tadd = 18\n" + "".join(
        "\t\t%sif = {\n\t\t\tlimit = { %s = { highest_held_title_tier = %s } }\n\t\t\tadd = %d\n\t\t}\n" % (
            "" if i == 0 else "else_", G, t, v) for i, (t, v) in enumerate(
            (("tier_county", 6), ("tier_duchy", 16), ("tier_kingdom", 28), ("tier_empire", 40)))).replace("\t\telse_if", "\t\telse_if"))
    s += good("clemency", "\t\tadd = 25\n")
    s += good("arms", "\t\tadd = 10\n\t\tif = {\n\t\t\tlimit = { %s = { is_at_war = yes } }\n\t\t\tadd = 15\n\t\t}\n" % G)
    s += good("artifact", "\t\tif = {\n\t\t\tlimit = { exists = scope:qpq_gift_artifact_cost }\n\t\t\tadd = scope:qpq_gift_artifact_cost\n\t\t}\n"
                          "\t\telse = {\n\t\t\tadd = 20\n\t\t}\n")
    s += good("church", "\t\tadd = 10\n")
    s += good("restraint", "\t\tadd = 8\n\t\tif = {\n\t\t\tlimit = { %s = { max_military_strength > { value = %s.max_military_strength multiply = 1.5 } } }\n"
                           "\t\t\tadd = 10\n\t\t}\n" % (G, R))
    s += "\tmin = 0\n"
    return s


