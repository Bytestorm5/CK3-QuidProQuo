def esc(s):
    return s.replace('"', '\\"')


def deal_words(t):
    """The player-facing word is "deal", not "pact" (keys, variables and scope names keep qpq_pact)."""
    import re
    for a, b in (("Pacts", "Deals"), ("pacts", "deals"), ("Pact", "Deal"), ("pact", "deal")):
        t = re.sub(r"(?<![\w])%s(?![\w])" % a, b, t)
    return t


