def block(snippet, level):
    """Dedent a snippet, convert 4-space indentation to tabs and indent it by `level` tabs."""
    if not snippet:
        return ""
    s = textwrap.dedent(snippet).strip("\n")
    out = []
    for line in s.split("\n"):
        stripped = line.lstrip(" ")
        n = (len(line) - len(stripped)) // 4
        line = "\t" * n + stripped
        out.append(("\t" * level + line) if line.strip() else "")
    return "\n".join(out) + "\n"


def write(path, text, bom=True):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write((BOM if bom else "") + text)


def payer_scope(k):
    return "scope:actor" if k["initiator"] == "payer" else "scope:recipient"


def agent_scope(k):
    return "scope:recipient" if k["initiator"] == "payer" else "scope:actor"


def target_expr(k):
    t = k["target"]
    if t == "char":
        return "scope:secondary_recipient"
    if t == "derived":
        return k["derive"]
    if t == "title":
        return "scope:target.holder"
    return None


