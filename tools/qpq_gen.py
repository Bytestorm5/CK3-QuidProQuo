def kind_check(k):
    return "var:qpq_kind = flag:%s" % k["key"]


def gen_triggers():
    out = HEADER
    for k in KINDS:
        key = k["key"]
        out += "#### %s\n" % k["name"]
        out += "qpq_k_%s_delivered_trigger = {\n%s}\n" % (key, block(k.get("deliver") or "always = no", 1))
        out += "qpq_k_%s_breached_trigger = {\n%s}\n" % (key, block(k.get("breach") or "always = no", 1))
        out += "qpq_k_%s_invalid_trigger = {\n%s}\n" % (key, block(k.get("invalid") or "always = no", 1))
        out += "qpq_k_%s_can_perform_trigger = {\n%s}\n\n" % (key, block(k.get("can_perform") or "always = no", 1))

    def dispatch(name, suffix, kinds):
        s = "%s = {\n\tOR = {\n" % name
        for k in kinds:
            s += "\t\tAND = {\n\t\t\t%s\n\t\t\tqpq_k_%s_%s = yes\n\t\t}\n" % (kind_check(k), k["key"], suffix)
        s += "\t}\n}\n\n"
        return s

    out += "############ Dispatch (root: a pact story or pact secret) ############\n"
    out += dispatch("qpq_kind_delivered_trigger", "delivered_trigger", [k for k in KINDS if k.get("deliver")])
